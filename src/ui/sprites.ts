/**
 * Pixel art des icônes et illustrations (dessinées pour Cadavre Exquis, aucun asset tiers).
 * Icônes: grille 12×12. `#` = couleur du texte, `o` = couleur d'accent atténuée, `.` = vide.
 */
export interface Sprite {
  w: number;
  h: number;
  rows: string[];
}

const mirror = (rows: string[]) => rows.map((r) => [...r].reverse().join(''));

function icon(rows: string[]): Sprite {
  const w = 12;
  const pad = 12 - rows.length;
  const top = Math.floor(pad / 2);
  const blank = '.'.repeat(w);
  return { w, h: 12, rows: [...Array(top).fill(blank), ...rows, ...Array(pad - top).fill(blank)] };
}

